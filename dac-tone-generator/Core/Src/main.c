/* Button (PC13, EXTI13): toggle LED2 and step to the next note.
   Overrides the weak HAL callback. */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  if (GPIO_Pin != Button_Pin)
    return;

  uint32_t now = HAL_GetTick();
  if (now - last_press < DEBOUNCE_MS)
    return;
  last_press = now;

  HAL_GPIO_TogglePin(LED2_GPIO_Port, LED2_Pin);

  /* Changing the timer period changes the sample rate, and therefore the pitch.
     ARR preload is enabled, so the new value applies from the next update event. */
  tone_index = (tone_index + 1U) % NUM_TONES;
  __HAL_TIM_SET_AUTORELOAD(&htim2, tone_arr[tone_index]);
}

