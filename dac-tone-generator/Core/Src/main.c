/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_DAC1_Init();
  MX_TIM2_Init();
  /* USER CODE BEGIN 2 */
  /* Build the sine table. Centred at mid-scale (128) with an amplitude of 85,
     i.e. about 2/3 of the 8-bit range, to avoid clipping under the speaker load. */
  for (int i = 0; i < SINE_N; i++)
  {
    float s = arm_sin_f32(2.0f * PI * (float)i / (float)SINE_N);
    sine[i] = (uint8_t)(128.0f + 85.0f * s + 0.5f);
  }

  /* TIM2 runs on APB1. Timer clocks are doubled when the APB1 prescaler is not 1. */
  uint32_t f_timer = HAL_RCC_GetPCLK1Freq();
  if ((RCC->CFGR & RCC_CFGR_PPRE1) != RCC_CFGR_PPRE1_DIV1)
    f_timer *= 2U;

  /* At 120 MHz: 3582 (C6), 2844 (E6), 2391 (G6) */
  for (int k = 0; k < NUM_TONES; k++)
    tone_arr[k] = (uint32_t)((float)f_timer / ((float)SINE_N * tone_hz[k]) + 0.5f) - 1U;

  __HAL_TIM_SET_AUTORELOAD(&htim2, tone_arr[0]);

#if USE_DMA
  /* DMA must be added to DAC1 in CubeMX, otherwise there is no handle */
  if (hdac1.DMA_Handle1 == NULL)
    Error_Handler();

  /* Start the DAC/DMA before the timer so data is ready on the first trigger.
     The timer runs without its interrupt; its TRGO drives the DAC directly. */
  HAL_DAC_Start_DMA(&hdac1, DAC_CHANNEL_1, (uint32_t *)sine, SINE_N, DAC_ALIGN_8B_R);
  HAL_TIM_Base_Start(&htim2);
#else
  /* Samples are written in HAL_TIM_PeriodElapsedCallback */
  HAL_DAC_Start(&hdac1, DAC_CHANNEL_1);
  HAL_TIM_Base_Start_IT(&htim2);
#endif
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    /* Nothing to do: output is driven by TIM2 (and DMA), the button by EXTI */
  }
  /* USER CODE END 3 */
}

